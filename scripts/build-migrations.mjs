#!/usr/bin/env node
/**
 * Regenerate supabase/ALL-MIGRATIONS.sql from supabase/migrations/*.sql.
 *
 *   npm run db:bundle
 *
 * The bundle exists for the Supabase SQL Editor, where there is no migration
 * runner — you paste one file and run it. It was previously maintained by
 * hand, drifted nine migrations behind, and still described itself as
 * generated. A stale bundle is worse than none: it applies cleanly and leaves
 * a partial schema, which looks like success.
 *
 * Every migration is idempotent, so re-running the bundle is safe.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'supabase/migrations';
const OUT = 'supabase/ALL-MIGRATIONS.sql';

const files = readdirSync(DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort();

if (!files.length) {
  console.error(`No migrations found in ${DIR}`);
  process.exit(1);
}

/** "20260913000100_phase01_profiles_and_audit.sql" -> "Phase 01 — profiles and audit". */
function describe(file) {
  const m = /^\d+_phase(\d+)_(.+)\.sql$/.exec(file);
  if (!m) return file.replace(/\.sql$/, '').replace(/_/g, ' ');
  const words = m[2].replace(/_/g, ' ');
  return `Phase ${m[1]} — ${words}`;
}

const contents = files.map((f) => ({
  file: f,
  sql: readFileSync(join(DIR, f), 'utf8').trimEnd(),
}));

const index = contents
  .map((c, i) => `--   ${String(i + 1).padStart(2, ' ')}. ${describe(c.file)}`)
  .join('\n');

const header = `-- =============================================================================
-- HelloPera — all migrations, in order.
--
-- GENERATED by scripts/build-migrations.mjs. Do not edit by hand; run
-- \`npm run db:bundle\` after adding a migration.
--
-- Paste this ENTIRE file into the Supabase SQL Editor and Run. Every statement
-- is idempotent, so re-running it is safe.
--
${index}
--
-- Prefer \`npm run db:migrate\` where you have DATABASE_URL: it applies each
-- file in its own transaction and records what ran. This bundle is for the
-- SQL Editor, which has no runner.
--
-- After this completes, run supabase/VERIFY-RLS.sql to confirm RLS is enforced.
-- =============================================================================
`;

const body = contents
  .map(
    (c) => `

-- ======================================================================
-- ${c.file}
-- ======================================================================

${c.sql}`,
  )
  .join('\n');

writeFileSync(OUT, `${header}${body}\n`);
console.log(`Wrote ${OUT} from ${files.length} migrations.`);
